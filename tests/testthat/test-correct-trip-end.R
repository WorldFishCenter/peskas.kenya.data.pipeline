test_that("landing times typed on a 12-hour clock or the wrong day are corrected", {
  t <- function(x) lubridate::ymd_hms(x, tz = "Africa/Nairobi")
  start <- t(c("2025-04-27 07:00:00", "2025-04-27 18:00:00", "2025-04-27 07:00:00",
               "2025-04-27 07:00:00", "2025-04-27 16:00:00", "2025-04-28 07:00:00", NA))
  end <- t(c("2025-04-27 01:30:00", "2025-04-27 05:00:00", "2025-04-27 13:30:00",
             "2025-04-27 07:00:00", "2025-04-27 13:00:00", "2025-04-27 10:00:00", "2025-04-27 01:00:00"))
  expect_equal(
    correct_trip_end(start, end),
    t(c("2025-04-27 13:30:00", "2025-04-28 05:00:00", "2025-04-27 13:30:00",
        "2025-04-27 07:00:00", "2025-04-27 13:00:00", "2025-04-27 10:00:00", "2025-04-27 01:00:00"))
  )
})
